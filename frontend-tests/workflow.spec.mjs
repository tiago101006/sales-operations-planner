const password = process.env.SOP_UI_PASSWORD;
const login = async (page, email) => {
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.locator('.shell')).toBeVisible();
};
const logout = async page => {
  await page.getByRole('button', { name: 'Terminar sessão' }).click();
  await expect(page.getByRole('heading', { name: 'Entrar na aplicação' })).toBeVisible();
};
const postResponse = (page, suffix) => page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/v1' + suffix);
const modal = page => page.getByRole('dialog');

