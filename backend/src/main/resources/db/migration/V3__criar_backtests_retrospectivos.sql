-- Simulacoes historicas separadas das execucoes operacionais e dos planos.
CREATE TABLE backtest (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    lote_id BIGINT NOT NULL,
    lote_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    tipo_serie ENUM('VENDAS','CONSUMO') NOT NULL,
    modo ENUM('SIMULACAO_RETROSPETIVA') NOT NULL DEFAULT 'SIMULACAO_RETROSPETIVA',
    primeiro_corte DATE NOT NULL,
    ultimo_corte DATE NOT NULL,
    horizonte_meses SMALLINT NOT NULL,
    corte_realizados DATETIME(6) NOT NULL,
    parametros JSON NOT NULL,
    versao_mm VARCHAR(80) NOT NULL,
    versao_ets VARCHAR(80) NOT NULL,
    versao_calculo VARCHAR(80) NOT NULL,
    estado ENUM('EM_EXECUCAO','CONCLUIDO') NOT NULL,
    criado_por BIGINT NOT NULL,
    criado_em DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    concluido_em DATETIME(6) NULL,
    UNIQUE KEY uk_backtest_lote (id,lote_id),
    CONSTRAINT ck_backtest_cortes CHECK (DAYOFMONTH(primeiro_corte)=1 AND DAYOFMONTH(ultimo_corte)=1 AND ultimo_corte>=primeiro_corte),
    CONSTRAINT ck_backtest_horizonte CHECK (horizonte_meses BETWEEN 1 AND 12),
    CONSTRAINT fk_backtest_lote FOREIGN KEY (lote_id) REFERENCES lote(id),
    CONSTRAINT fk_backtest_autor FOREIGN KEY (criado_por) REFERENCES utilizador(id)
) ENGINE=InnoDB;

CREATE TABLE backtest_celula (
    backtest_id BIGINT NOT NULL,
    lote_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    corte DATE NOT NULL,
    periodo DATE NOT NULL,
    horizonte SMALLINT NOT NULL,
    observacao_id BIGINT NULL,
    previsao_mm DECIMAL(18,4) NULL,
    previsao_ets DECIMAL(18,4) NULL,
    estado_mm ENUM('PREVISTO','INSUFICIENTE','ERRO') NOT NULL,
    estado_ets ENUM('PREVISTO','INSUFICIENTE','ERRO') NOT NULL,
    parametros_mm JSON NOT NULL,
    parametros_ets JSON NOT NULL,
    diagnostico_mm VARCHAR(1000) NULL,
    diagnostico_ets VARCHAR(1000) NULL,
    PRIMARY KEY (backtest_id,produto_id,corte,horizonte),
    CONSTRAINT ck_bt_celula_periodos CHECK (DAYOFMONTH(corte)=1 AND horizonte BETWEEN 1 AND 12 AND periodo=DATE_ADD(corte,INTERVAL horizonte MONTH)),
    CONSTRAINT ck_bt_celula_mm CHECK ((estado_mm='PREVISTO' AND previsao_mm IS NOT NULL AND previsao_mm>=0) OR (estado_mm IN ('INSUFICIENTE','ERRO') AND previsao_mm IS NULL)),
    CONSTRAINT ck_bt_celula_ets CHECK ((estado_ets='PREVISTO' AND previsao_ets IS NOT NULL AND previsao_ets>=0) OR (estado_ets IN ('INSUFICIENTE','ERRO') AND previsao_ets IS NULL)),
    CONSTRAINT fk_bt_celula_cabecalho FOREIGN KEY (backtest_id,lote_id) REFERENCES backtest(id,lote_id),
    CONSTRAINT fk_bt_celula_produto FOREIGN KEY (produto_id) REFERENCES produto(id),
    CONSTRAINT fk_bt_celula_realizado FOREIGN KEY (observacao_id,lote_id,produto_id,periodo) REFERENCES observacao(id,lote_id,produto_id,periodo)
) ENGINE=InnoDB;
